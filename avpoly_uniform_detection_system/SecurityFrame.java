    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String security = jPasswordField1.getText().trim();
        
        if(security.isEmpty()){
            JOptionPane.showMessageDialog(null,"Security Key should not be empty");
        }
        
        else if(security.equals("nandini")){
            this.dispose();
            StaffRegistrationFrame s = new StaffRegistrationFrame();
            Dimension d = Toolkit.getDefaultToolkit().getScreenSize();
            s.setVisible(true);
            s.setSize(d);
        }
        
        else{
            JOptionPane.showMessageDialog(null,"Security Key is Incorrect");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

